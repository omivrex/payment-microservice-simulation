import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

/**
 * yarn gen:secrets — writes freshly generated placeholder secrets into .env
 * (creating it from .env.example if needed). See docs/01-architecture.md §1.6.
 *
 * Existing non-empty keys are KEPT unless --force is passed: replacing them on an
 * existing database makes stored card numbers and webhook secrets unreadable and
 * invalidates every issued secret API key.
 */

export const PLACEHOLDER_COMMENT = `# --- Secrets (placeholders generated by \`yarn gen:secrets\`) ---
# These are placeholder keys, randomly generated for local use. Replace them with your own
# random values before any shared or production use, e.g. \`openssl rand -base64 32\`.
# Format rules (the server refuses to start otherwise):
#   ENCRYPTION_KEYS  = v1:<exactly 32 random bytes, base64>   (32 bytes -> 44 base64 chars)
#   HASHING_SECRET   = <at least 32 random bytes, base64>
# Changing them later makes existing encrypted data unreadable and invalidates issued secret keys.
# Keep them secret. Never commit .env.`;

const KEYS = ['ENCRYPTION_KEYS', 'ENCRYPTION_ACTIVE_KEY_ID', 'HASHING_SECRET'] as const;

export interface ApplyResult {
  content: string;
  set: string[];
  kept: string[];
}

/** Sets the three secret variables in .env content. Pure, so it can be tested. */
export function applySecrets(content: string, options: { force: boolean; random?: () => Buffer } = { force: false }): ApplyResult {
  const random = options.random ?? (() => randomBytes(32));
  const values: Record<(typeof KEYS)[number], string> = {
    ENCRYPTION_KEYS: `v1:${random().toString('base64')}`,
    ENCRYPTION_ACTIVE_KEY_ID: 'v1',
    HASHING_SECRET: random().toString('base64'),
  };
  // A kept ENCRYPTION_KEYS keeps its own active key id; only reset the id when the keys are regenerated.
  const set: string[] = [];
  const kept: string[] = [];
  let out = content;

  for (const key of KEYS) {
    const line = new RegExp(`^${key}=(.*)$`, 'm');
    const current = line.exec(out)?.[1]?.trim() ?? '';
    const encryptionKept = key === 'ENCRYPTION_ACTIVE_KEY_ID' && kept.includes('ENCRYPTION_KEYS');
    if ((current && !options.force && key !== 'ENCRYPTION_ACTIVE_KEY_ID') || encryptionKept) {
      kept.push(key);
      continue;
    }
    if (line.test(out)) out = out.replace(line, `${key}=${values[key]}`);
    else out = `${out.replace(/\n*$/, '\n')}${key}=${values[key]}\n`;
    set.push(key);
  }

  if (!out.includes(PLACEHOLDER_COMMENT) && set.some((k) => k !== 'ENCRYPTION_ACTIVE_KEY_ID')) {
    out = out.replace(/^ENCRYPTION_KEYS=/m, `${PLACEHOLDER_COMMENT}\nENCRYPTION_KEYS=`);
  }
  return { content: out, set, kept };
}

function main(): void {
  const force = process.argv.includes('--force');
  const source = existsSync('.env') ? '.env' : existsSync('.env.example') ? '.env.example' : null;
  const original = source ? readFileSync(source, 'utf8') : '';
  const { content, set, kept } = applySecrets(original, { force });
  writeFileSync('.env', content, { mode: 0o600 });

  console.log(`.env ${source === '.env' ? 'updated' : 'created'}.`);
  if (set.length) console.log(`  set:  ${set.join(', ')} (placeholder values, see the comment in .env)`);
  if (kept.length) console.log(`  kept: ${kept.join(', ')} (already set; use --force to replace, which breaks existing data)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
